"""Phase P0.6.F — Market Perspective™ (Cultural Design Intelligence™).

NOT localization. NOT translation. Cultural REPOSITIONING.

The same project produces different emotional narratives, positioning,
vocabulary and investment framing depending on the target market.

The profile loaded from `market_positioning_profiles` is the source of
truth — it feeds the LLM system prompt with the market's native cultural
context (focus areas, vocabulary, forbidden patterns, system_brief).
"""
import os
import re
import json
import uuid
import logging
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field

from database import db
from core.tenant_context import get_tenant_context

logger = logging.getLogger(__name__)
router = APIRouter(tags=["market-perspectives"])


# ─── Profile loading ─────────────────────────────────────────────────────

def _load_profile(c, locale_code: str) -> Optional[Dict[str, Any]]:
    """Load a locale profile (IT_IT, EN_US, EN_GB, EN_AE, …)."""
    r = (c.table("locale_profiles").select("*")
         .eq("locale_code", locale_code.upper()).limit(1).execute())
    return r.data[0] if r.data else None


# Market-intent-preserving fallback chain — never collapse EN_AE prestige
# into IT_IT craftsmanship etc.
_FALLBACK_CHAIN: Dict[str, List[str]] = {
    "EN_AE": ["EN_GB", "EN_US"],
    "EN_GB": ["EN_US"],
    "EN_US": ["EN_GB"],
    "FR_FR": ["IT_IT", "EN_GB"],
    "DE_DE": ["EN_GB"],
    "ES_ES": ["IT_IT", "EN_GB"],
    "IT_IT": ["EN_GB"],
}


def _resolve_profile(c, locale_code: str) -> Optional[Dict[str, Any]]:
    p = _load_profile(c, locale_code)
    if p:
        return p
    for alt in _FALLBACK_CHAIN.get(locale_code, []):
        alt_p = _load_profile(c, alt)
        if alt_p:
            logger.warning(
                f"perspective locale fallback {locale_code} → {alt} "
                f"(closest cultural register)"
            )
            return alt_p
    return None


def _load_all_profiles(c) -> List[Dict[str, Any]]:
    r = (c.table("locale_profiles")
         .select("locale_code, language, market, display_name, "
                 "emotional_style, focus")
         .order("locale_code").execute())
    return r.data or []


# ─── LLM composer (profile-driven) ───────────────────────────────────────

_PERSPECTIVE_SYSTEM_TEMPLATE = """You are an editorial creative director
repositioning the SAME interior design project for a different locale-native
audience. You are NOT translating. You are NOT softening or escalating tone.
You are NATIVELY recomposing the narrative the way a senior creative
director writing for THAT specific market would write it.

CRITICAL: EN_US, EN_GB and EN_AE all use English, but they are
fundamentally different cultural positionings — never share vocabulary
across them.

═══ LOCALE PROFILE ({locale_code}) ═══
{system_brief}

EMOTIONAL STYLE:      {emotional_style}
LUXURY STYLE:         {luxury_style}
HOSPITALITY STYLE:    {hospitality_style}
EDITORIAL TONE:       {editorial_tone}
CTA STYLE:            {cta_style}
INVESTMENT LANGUAGE:  {investment_language}
ATMOSPHERE LANGUAGE:  {atmosphere_language}

FOCUS AREAS (use these as the conceptual backbone):
  {focus}

VOCABULARY (prefer these terms; never use generic alternatives):
  {vocabulary}

FORBIDDEN PATTERNS (do not use these, ever):
  {forbidden}

POSITIONING EXAMPLES (the tonal register we want):
  {examples}

═══ RULES ═══
• Reposition, do NOT translate. Even if the previous narrative is excellent
  in another locale, REWRITE it natively for this one.
• Write in this locale's language ({language}).
• NEVER mention AI, GPT, "generated by", or any system meta-language.
• Each section: 2–4 sentences of editorial prose. NO bullet points.
• Keep the project's material identity, moodboards and inspirations stable —
  only reposition the COMMUNICATION around them.
• Output: SINGLE valid JSON object, no markdown, no preamble.

JSON SHAPE:
{{
  "headline":             "evocative line, max 14 words, in this locale's language",
  "opening":              "...",
  "strategic_direction":  "...",
  "visual_inspirations":  "...",
  "material_language":    "...",
  "project_vision":       "...",
  "suggested_scope":      "...",
  "investment":           "...",
  "timeline":             "...",
  "signature":            "...",
  "positioning_summary":  "one-line summary of how this locale reads this project"
}}"""


def _build_system_prompt(profile: Dict[str, Any]) -> str:
    return _PERSPECTIVE_SYSTEM_TEMPLATE.format(
        locale_code=profile.get("locale_code", ""),
        system_brief=profile.get("system_brief", ""),
        emotional_style=profile.get("emotional_style", ""),
        luxury_style=profile.get("luxury_style", ""),
        hospitality_style=profile.get("hospitality_style", ""),
        editorial_tone=profile.get("editorial_tone", ""),
        cta_style=profile.get("cta_style", ""),
        investment_language=profile.get("investment_language", ""),
        atmosphere_language=profile.get("atmosphere_language", ""),
        focus=", ".join(profile.get("focus") or []),
        vocabulary=", ".join(profile.get("vocabulary_rules") or []),
        forbidden=", ".join(profile.get("forbidden_patterns") or []),
        examples="\n  ".join(profile.get("positioning_examples") or []),
        language=profile.get("language", "en"),
    )


def _build_user_msg(project_context: Dict[str, Any],
                    existing_sections: Dict[str, Any]) -> str:
    """Feed the LLM the stable project identity + the previous sections
    (as conceptual seed, NOT to translate). The model must REWRITE."""
    seed = {k: v for k, v in (existing_sections or {}).items()
            if k not in ("_locale", "_perspectives", "headline") and isinstance(v, str)}
    return (
        "═══ STABLE PROJECT IDENTITY (do not invent — use these signals) ═══\n"
        f"{json.dumps(project_context, ensure_ascii=False, indent=2, default=str)[:5500]}\n\n"
        "═══ PREVIOUS NARRATIVE (seed — DO NOT TRANSLATE, REPOSITION) ═══\n"
        f"{json.dumps(seed, ensure_ascii=False, indent=2)[:2500]}\n\n"
        "Recompose the editorial proposal natively for the market profile above. "
        "Output JSON only."
    )


def _gather_project_context(c, proposal: Dict[str, Any]) -> Dict[str, Any]:
    """Stable project identity — what does NOT change between markets."""
    pid = proposal["project_id"]
    tid = proposal["tenant_id"]
    ctx: Dict[str, Any] = {}
    try:
        pr = (c.table("projects").select("title, project_type, budget_range, timeline, description, metadata_json")
              .eq("id", pid).eq("tenant_id", tid).limit(1).execute().data or [])
        if pr:
            ctx["project"] = pr[0]
    except Exception:
        pass
    try:
        ins = (c.table("moodboard_candidates").select(
            "title, description, image_url, reference_type, advisor_note"
        ).eq("project_id", pid).eq("tenant_id", tid)
           .order("created_at", desc=True).limit(10).execute().data or [])
        ctx["inspirations"] = ins
    except Exception:
        pass
    try:
        rows = (c.table("material_registry").select(
            "name, category, finish, dominant_color, tags, metadata_json"
        ).eq("tenant_id", tid).eq("status", "active").limit(500).execute().data or [])
        ctx["materials"] = [{
            "name": r.get("name"), "category": r.get("category"),
            "finish": r.get("finish"), "color": r.get("dominant_color"),
            "tags": r.get("tags") or [],
        } for r in rows
            if pid in ((r.get("metadata_json") or {}).get("linked_project_ids") or [])]
    except Exception:
        pass
    return ctx


# ─── Models ──────────────────────────────────────────────────────────────

class SwitchPerspectiveIn(BaseModel):
    locale_code: str = Field(..., min_length=4, max_length=8,
                             description="Composite locale (IT_IT, EN_US, EN_GB, EN_AE, …)")
    set_active:  bool = Field(True, description="Push this perspective live on the proposal")


