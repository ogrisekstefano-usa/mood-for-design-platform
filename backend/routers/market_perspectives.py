@router.get("/market-perspectives/profiles")
def list_profiles_legacy(ctx=Depends(get_tenant_context)):
    return {"profiles": _load_all_profiles(db())}


@router.get("/proposals/{proposal_id}/perspectives")
def list_proposal_perspectives(proposal_id: str, ctx=Depends(get_tenant_context)):
    """All locale versions ever generated for this proposal + which is active."""
    c = db()
    pr = (c.table("proposals").select("id, tenant_id, market, locale_code")
          .eq("id", proposal_id).eq("tenant_id", ctx["tenant_id"])
          .limit(1).execute())
    if not pr.data:
        raise HTTPException(404, "proposal not found")
    rows = (c.table("proposal_market_versions").select(
        "id, locale_code, market_code, locale, headline, positioning_summary, "
        "generated_at, is_active"
    ).eq("proposal_id", proposal_id).eq("tenant_id", ctx["tenant_id"])
       .order("generated_at", desc=True).execute().data or [])
    return {
        "versions":      rows,
        "active_locale": pr.data[0].get("locale_code"),
        "active_market": pr.data[0].get("market"),
    }


@router.post("/proposals/{proposal_id}/perspective", status_code=201)
async def switch_perspective(proposal_id: str, body: SwitchPerspectiveIn,
                             ctx=Depends(get_tenant_context)):
    """Recompose the proposal narrative for `locale_code` using its
    Locale Profile. Saves a new version snapshot. If `set_active=True`
    (default), the proposal's live sections + locale fields are updated."""
    c = db()
    locale_code = body.locale_code.upper()

    # Load proposal
    pr = (c.table("proposals").select("*")
          .eq("id", proposal_id).eq("tenant_id", ctx["tenant_id"]).limit(1).execute())
    if not pr.data:
        raise HTTPException(404, "proposal not found")
    proposal = pr.data[0]

    # Load target locale profile (with market-intent-preserving fallback)
    profile = _resolve_profile(c, locale_code)
    if not profile:
        raise HTTPException(404, f"locale profile {locale_code} not found")
    # If a fallback kicked in, the effective locale is the profile we got.
    locale_code = profile["locale_code"]

    language = profile["language"]
    market   = profile["market"]
    project_ctx = _gather_project_context(c, proposal)
    existing_sections = proposal.get("sections") or {}

    # ── LLM call ────────────────────────────────────────────────────
    new_sections: Dict[str, Any] = {}
    positioning_summary: Optional[str] = None
    used_model = "fallback"
    key = os.environ.get("EMERGENT_LLM_KEY")
    if key:
        try:
            from emergentintegrations.llm.chat import LlmChat, UserMessage  # type: ignore
            chat = (
                LlmChat(
                    api_key=key,
                    session_id=f"persp-{proposal_id}-{locale_code}-{uuid.uuid4().hex[:8]}",
                    system_message=_build_system_prompt(profile),
                )
                .with_model("anthropic", "claude-sonnet-4-5-20250929")
                .with_params(max_tokens=2000)
            )
            raw = await chat.send_message(UserMessage(
                text=_build_user_msg(project_ctx, existing_sections),
            ))
            text = raw if isinstance(raw, str) else getattr(raw, "text", str(raw))
            m = re.search(r"\{[\s\S]*\}", text)
            if m:
                parsed = json.loads(m.group(0))
                # Whitelist editorial section keys
                allowed = {"headline", "opening", "strategic_direction",
                           "visual_inspirations", "material_language",
                           "project_vision", "suggested_scope", "investment",
                           "timeline", "signature"}
                for k, v in parsed.items():
                    if k in allowed and isinstance(v, str) and v.strip():
                        new_sections[k] = v.strip()
                positioning_summary = (parsed.get("positioning_summary") or "").strip() or None
                used_model = "claude-sonnet-4-5"
        except Exception as e:
            logger.warning(f"perspective LLM fallback for {locale_code}: {e}")

    if not new_sections:
        # Minimal fallback: keep existing copy but tag it
        new_sections = {k: v for k, v in existing_sections.items() if isinstance(v, str)}
        new_sections["headline"] = (
            new_sections.get("headline") or "Direzione editoriale"
        )

    # Persist _locale (lowercase language for chrome) so the editor chrome adapts
    new_sections["_locale"] = language
    new_sections["_locale_code"] = locale_code
    headline = new_sections.get("headline") or proposal.get("title") or "—"

    # ── Snapshot in proposal_market_versions ───────────────────────
    snap_id = str(uuid.uuid4())
    iso = datetime.now(timezone.utc).isoformat()
    try:
        if body.set_active:
            c.table("proposal_market_versions").update({"is_active": False}) \
                .eq("proposal_id", proposal_id).eq("tenant_id", ctx["tenant_id"]) \
                .execute()
        existing = (c.table("proposal_market_versions").select("id")
                    .eq("proposal_id", proposal_id).eq("locale_code", locale_code)
                    .eq("tenant_id", ctx["tenant_id"]).limit(1).execute())
        version_payload = {
            "tenant_id":           ctx["tenant_id"],
            "proposal_id":         proposal_id,
            "locale_code":         locale_code,
            "market_code":         market,   # legacy column, kept for analytics
            "locale":              language,
            "sections":            new_sections,
            "headline":            headline,
            "positioning_summary": positioning_summary,
            "generated_by":        ctx["profile_id"],
            "generated_at":        iso,
            "is_active":           body.set_active,
        }
        if existing.data:
            snap_id = existing.data[0]["id"]
            c.table("proposal_market_versions").update(version_payload) \
                .eq("id", snap_id).execute()
        else:
            version_payload["id"] = snap_id
            c.table("proposal_market_versions").insert(version_payload).execute()
    except Exception as e:
        logger.warning(f"perspective snapshot failed: {e}")

    if body.set_active:
        try:
            c.table("proposals").update({
                "sections":    new_sections,
                "market":      market,
                "locale_code": locale_code,
                "title":       headline[:200],
                "updated_at":  iso,
            }).eq("id", proposal_id).eq("tenant_id", ctx["tenant_id"]).execute()
        except Exception as e:
            logger.warning(f"perspective live-update failed: {e}")

    return {
        "ok":                  True,
        "version_id":          snap_id,
        "locale_code":         locale_code,
        "market":              market,
        "language":            language,
        "headline":            headline,
        "positioning_summary": positioning_summary,
        "model_used":          used_model,
    }
